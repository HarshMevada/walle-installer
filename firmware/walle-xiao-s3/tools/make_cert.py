#!/usr/bin/env python3
"""Create the self-signed certificate for Chitu's https phone console.

Writes chitu_cert.h next to the board sources. Run once before building
(the GitHub build does this automatically). Phones show a one-time
"not private" warning for it because it is not signed by a public authority.
"""
import os, subprocess, sys, tempfile

out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "chitu_cert.h")
with tempfile.TemporaryDirectory() as d:
    key, crt = os.path.join(d, "key.pem"), os.path.join(d, "cert.pem")
    subprocess.run(["openssl", "req", "-x509", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:prime256v1",
                    "-nodes", "-days", "3650", "-subj", "/CN=chitu", "-keyout", key, "-out", crt],
                   check=True, capture_output=True)
    k, c = open(key).read(), open(crt).read()

def c_str(name, pem):
    lines = "\n".join('    "%s\\n"' % line for line in pem.strip().splitlines())
    return "static const char %s[] =\n%s;\n" % (name, lines)

with open(out, "w") as f:
    f.write("// Generated by tools/make_cert.py - self-signed certificate for the phone console\n#pragma once\n\n")
    f.write(c_str("kChituCertPem", c) + "\n" + c_str("kChituKeyPem", k))
print("wrote", out)
