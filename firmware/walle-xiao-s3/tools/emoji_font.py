# Render monochrome Noto Emoji glyphs to a 1-bpp LVGL fmt_txt font (fallback font for labels)
import sys, glob
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont
src, out, size = sys.argv[1], sys.argv[2], int(sys.argv[3]); THR = int(sys.argv[4]) if len(sys.argv) > 4 and sys.argv[4].isdigit() else 70
EMOJI = ("😀😃😄😁😆😅😂🤣😊😇🙂🙃😉😍🥰😘😋😛😜🤪😎🤩🥳😏😒😞😔😟😕🙁☹😣😖😫😩🥺😢😭😤😠😡🤬🤯😳"
         "😱😨😰😥😓🤗🤔🤭🤫😶😐😑😬🙄😯😮😲🥱😴🤤😪😵🤐🥴🤢🤮🤧😷🤒🤕😈👻💀🤖👽💩😺"
         "👍👎👋👏🙌🙏💪✌👌🤞👉👈👆👇✋🤝👀👂"
         "❤🧡💛💚💙💜🖤🤍💔💕💖💯💤💢💥💫💬❓❗✅❌⭐🌟✨⚡🔥💧☀🌞🌙☁🌈❄☔"
         "🎉🎊🎂🎁🎈🎵🎶🎮⚽🏀🏆🍕🍔🍟🍦🍩🍪🍫🍎🍌🍉☕🍵🌹🌸🌻🍀🐶🐱🐭🐰🦊🐻🐼🐯🦁🐮🐷🐸🐵🐔🐧🐦🦋🐝🐢🐍🐟🐬"
         "🏠🚗🚀✈🚲⏰📱💻📷🔋💡📚✏🔔🎤🎧📞💰🎯🚦⚠")
cps = sorted({ord(c) for c in EMOJI})
files = sorted(glob.glob(src + "/noto-emoji-*-700-normal.woff"))
cmap_file = {}
for f in files:
    for cp in TTFont(f).getBestCmap():
        cmap_file.setdefault(cp, f)
glyphs = []
for cp in cps:
    f = cmap_file.get(cp)
    if not f: print("missing", hex(cp)); continue
    big = size * 8
    font = ImageFont.truetype(f, big)
    img = Image.new("L", (big * 2, big * 2), 0)
    ImageDraw.Draw(img).text((big // 2, big // 2), chr(cp), font=font, fill=255)
    bb = img.getbbox()
    if not bb: print("empty", hex(cp)); continue
    img = img.crop(bb)
    w, h = img.size; s = max(w, h)
    sq = Image.new("L", (s, s), 0); sq.paste(img, ((s - w) // 2, (s - h) // 2))
    sm = sq.resize((size, size), Image.LANCZOS)
    px = [[1 if sm.getpixel((x, y)) > THR else 0 for x in range(size)] for y in range(size)]
    glyphs.append((cp, px))
if "--preview" in sys.argv:
    for cp, px in [g for g in glyphs if chr(g[0]) in "😀😂😍😢❤👍🔥🤖"]:
        print(chr(cp)); print("\n".join("".join("#" if v else "." for v in r) for r in px))
# bitmap (plain 1bpp, rows packed continuously like lv_font_conv)
bitmap, gdsc = [], ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}"]
for cp, px in glyphs:
    idx = len(bitmap); bits = [v for r in px for v in r]
    bits += [0] * (-len(bits) % 8)
    bitmap += [int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8)]
    gdsc.append(f"    {{.bitmap_index = {idx}, .adv_w = {(size + 1) * 16}, .box_w = {size}, .box_h = {size}, .ofs_x = 0, .ofs_y = -2}}")
lo = [g for g in glyphs if g[0] < 0x10000]; hi = [g for g in glyphs if g[0] >= 0x10000]
def lst(gs, base): return ", ".join(hex(cp - base) for cp, _ in gs)
lo_base, hi_base = lo[0][0], hi[0][0]
with open(out, "w") as o:
    o.write(f"""// Generated by tools/emoji_font.py from Noto Emoji (SIL OFL 1.1) - {len(glyphs)} emoji, {size}px, 1 bpp
#include <lvgl.h>
#include "chitu_emoji_font.h"

static const uint8_t glyph_bitmap[] = {{
{", ".join(hex(b) for b in bitmap)}
}};
static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{(","+chr(10)).join(gdsc)}
}};
static const uint16_t unicode_list_lo[] = {{ {lst(lo, lo_base)} }};
static const uint16_t unicode_list_hi[] = {{ {lst(hi, hi_base)} }};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = {lo_base:#x}, .range_length = {lo[-1][0] - lo_base + 1}, .glyph_id_start = 1,
     .unicode_list = unicode_list_lo, .glyph_id_ofs_list = NULL, .list_length = {len(lo)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},
    {{.range_start = {hi_base:#x}, .range_length = {hi[-1][0] - hi_base + 1}, .glyph_id_start = {1 + len(lo)},
     .unicode_list = unicode_list_hi, .glyph_id_ofs_list = NULL, .list_length = {len(hi)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},
}};
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL,
    .kern_scale = 0, .cmap_num = 2, .bpp = 1, .kern_classes = 0, .bitmap_format = 0,
}};
const lv_font_t chitu_emoji_font = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {size + 1}, .base_line = 2, .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = 0, .underline_thickness = 0, .dsc = &font_dsc,
}};
""")
print(len(glyphs), "glyphs,", len(bitmap), "bytes")
