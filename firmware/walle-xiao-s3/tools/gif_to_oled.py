#!/usr/bin/env python3
"""Convert the Wall-E eye GIFs (240x100 colour) into 1-bit frames for a 128x64 OLED.

Usage: python gif_to_oled.py <folder with the .gif files> <output folder>
Writes walle_eye_frames.h / walle_eye_frames.c (frames are de-duplicated).

Shading: the bright body of the eye is solid, the darker 3D rim of the original
is drawn as a 50% checker pattern, which is the closest a 1-bit screen gets to the glow.
"""
import os, sys
from PIL import Image, ImageSequence

W, H = 128, 53            # 240x100 scaled to keep the 2.4:1 shape
STRIDE = (W + 7) // 8
BODY_LEVEL = 150          # grey level >= this -> solid lit pixel
RIM_LEVEL = 60            # between RIM_LEVEL and BODY_LEVEL -> checker (rim / glow)

# GIF file -> animation name used by the firmware
ANIMS = [
    ("eyes_nomal.gif", "normal"),          # blink
    ("happy_eyes.gif", "happy"),
    ("sad_eyes.gif", "sad"),
    ("angry_eyes.gif", "angry"),
    ("suspicious_eyes.gif", "suspicious"),
    ("eyes_shake.gif", "shake"),           # squeeze shut and reopen
    ("nhin tren trai.gif", "look_up_left"),
    ("nhin tren phai.gif", "look_up_right"),
    ("nhin duoi trai.gif", "look_down_left"),
    ("nhin duoi phai.gif", "look_down_right"),
]


def convert_frame(img):
    g = img.convert("L").resize((W, H), Image.LANCZOS)
    px = g.load()
    data = bytearray(STRIDE * H)
    for y in range(H):
        for x in range(W):
            v = px[x, y]
            lit = v >= BODY_LEVEL or (v >= RIM_LEVEL and (x + y) % 2 == 0)
            if lit:
                data[y * STRIDE + (x >> 3)] |= 0x80 >> (x & 7)
    return bytes(data)


def main(src, out):
    frames, index = [], {}
    anims = []
    for fname, name in ANIMS:
        im = Image.open(os.path.join(src, fname))
        ids, delays = [], []
        for fr in ImageSequence.Iterator(im):
            d = convert_frame(fr.convert("RGB"))
            if d not in index:
                index[d] = len(frames)
                frames.append(d)
            ids.append(index[d])
            delays.append(max(20, int(fr.info.get("duration", 80))))
        anims.append((name, ids, delays))
        print(f"{name:16s} {len(ids):3d} frames  {sum(delays)} ms")
    print(f"unique frames: {len(frames)}  ({len(frames) * STRIDE * H / 1024:.1f} KB)")

    with open(os.path.join(out, "walle_eye_frames.h"), "w") as f:
        f.write(f"""// Generated by tools/gif_to_oled.py - do not edit by hand
#pragma once
#include <stdint.h>

#ifdef __cplusplus
extern "C" {{
#endif

#define WALLE_EYE_W      {W}
#define WALLE_EYE_H      {H}
#define WALLE_EYE_STRIDE {STRIDE}

typedef struct {{
    const char* name;
    uint16_t frame_count;
    const uint16_t* frames;     // indexes into walle_eye_frame_data
    const uint16_t* delays_ms;
}} walle_eye_anim_t;

extern const uint8_t walle_eye_frame_data[][WALLE_EYE_STRIDE * WALLE_EYE_H];
extern const walle_eye_anim_t walle_eye_anims[];
extern const int walle_eye_anim_count;

#ifdef __cplusplus
}}
#endif
""")
    with open(os.path.join(out, "walle_eye_frames.c"), "w") as f:
        f.write("// Generated by tools/gif_to_oled.py from the Wall-E AI eye GIFs - do not edit by hand\n")
        f.write('#include "walle_eye_frames.h"\n#include "config.h"\n#if WALLE_EYES_STYLE == 1\n\n')
        f.write(f"const uint8_t walle_eye_frame_data[{len(frames)}][WALLE_EYE_STRIDE * WALLE_EYE_H] = {{\n")
        for d in frames:
            f.write("    {")
            f.write(",".join(f"0x{b:02x}" for b in d))
            f.write("},\n")
        f.write("};\n\n")
        for name, ids, delays in anims:
            f.write(f"static const uint16_t {name}_frames[] = {{{','.join(map(str, ids))}}};\n")
            f.write(f"static const uint16_t {name}_delays[] = {{{','.join(map(str, delays))}}};\n")
        f.write("\nconst walle_eye_anim_t walle_eye_anims[] = {\n")
        for name, ids, delays in anims:
            f.write(f'    {{"{name}", {len(ids)}, {name}_frames, {name}_delays}},\n')
        f.write("};\n")
        f.write(f"const int walle_eye_anim_count = {len(anims)};\n")
        f.write("\n#endif  // WALLE_EYES_STYLE == 1\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
